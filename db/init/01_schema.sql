-- Schema for S-Group Learning Platform.
-- Runs automatically the first time the Postgres container starts with an empty volume.

create table users (
	id integer generated by default as identity primary key,
	name varchar(50) not null,
	email varchar(255) not null,
	password_hash varchar(255) not null,
	age integer,
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now(),

	constraint uq_users_email unique (email),
	constraint ck_users_age check (age between 1 and 120)
);

create table roles (
	id integer generated by default as identity primary key,
	name varchar(50) not null,
	description text,

	constraint uq_roles_name unique (name)
);

create table permissions (
	id integer generated by default as identity primary key,
	name varchar(50) not null,
	description text,

	constraint uq_permissions_name unique (name)
);

create table user_roles (
	user_id integer not null,
	role_id integer not null,

	constraint pk_user_roles primary key (user_id, role_id),

	constraint fk_user_roles_user foreign key (user_id) references users(id) on delete cascade,
	constraint fk_user_roles_role foreign key (role_id) references roles(id) on delete restrict
);

create index idx_user_roles_role on user_roles(role_id);

create table role_permissions (
	role_id integer not null,
	permission_id integer not null,

	constraint pk_role_permissions primary key (role_id, permission_id),

	constraint fk_role_permissions_role foreign key (role_id) references roles(id) on delete cascade,
	constraint fk_role_permissions_permission foreign key (permission_id) references permissions(id) on delete restrict
);

create index idx_role_permissions_permission on role_permissions(permission_id);

create table classes (
	id integer generated by default as identity primary key,
	name varchar(100) not null,
	description text,
	start_date date not null,
	end_date date,
	mentor_id integer,
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now(),

	constraint fk_classes_mentor foreign key (mentor_id) references users(id) on delete set null,

	constraint uq_classes_name unique (name),
	constraint ck_classes_end_date check (end_date >= start_date)
);

create index idx_classes_mentor on classes(mentor_id);

create table class_members (
	class_id integer not null,
	member_id integer not null,
	joined_at timestamptz not null default now(),

	constraint pk_class_members primary key (class_id, member_id),

	constraint fk_class_members_class foreign key (class_id) references classes(id) on delete cascade,
	constraint fk_class_members_member foreign key (member_id) references users(id) on delete cascade
);

create index idx_class_members_member on class_members(member_id);

create table lessons (
	id integer generated by default as identity primary key,
	class_id integer not null,
	title varchar(255) not null,
	content text,
	lesson_order integer not null,
	created_by integer,
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now(),

	constraint fk_lessons_class foreign key (class_id) references classes(id) on delete cascade,
	constraint fk_lessons_created_by foreign key (created_by) references users(id) on delete set null,

	constraint uq_lessons_class_order unique (class_id, lesson_order),

	constraint ck_lessons_order check (lesson_order > 0)
);

create table assignments (
	id integer generated by default as identity primary key,
	class_id integer not null,
	title varchar(255) not null,
	description text,
	deadline timestamptz not null,
	maximum_score numeric(4,2) not null,
	created_by integer,
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now(),

	constraint fk_assignments_class foreign key (class_id) references classes(id) on delete cascade,
	constraint fk_assignments_created_by foreign key (created_by) references users(id) on delete set null,

	constraint ck_assignments_maximum_score check (maximum_score > 0 and maximum_score <= 10)
);

create index idx_assignments_class on assignments(class_id);

create table lesson_progress (
	id integer generated by default as identity primary key,
	lesson_id integer not null,
	member_id integer not null,
	completed_at timestamptz not null default now(),

	constraint fk_lesson_progress_lesson foreign key (lesson_id) references lessons(id) on delete cascade,
	constraint fk_lesson_progress_member foreign key (member_id) references users(id) on delete cascade,

	constraint uq_lesson_progress_lesson_member unique (lesson_id, member_id)
);

create index idx_lesson_progress_member_id on lesson_progress(member_id);

create table submissions (
	id integer generated by default as identity primary key,
	assignment_id integer not null,
	member_id integer not null,
	content text,
	repository_url varchar(2048),
	submitted_at timestamptz not null default now(),
	score numeric(4,2),
	feedback text,
	reviewed_at timestamptz,
	reviewed_by integer,
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now(),

	constraint fk_submissions_assignment foreign key (assignment_id) references assignments(id) on delete cascade,
	constraint fk_submissions_member foreign key (member_id) references users(id) on delete cascade,
	constraint fk_submissions_reviewed_by foreign key (reviewed_by) references users(id) on delete set null,

	constraint uq_submissions_assignment_member unique (assignment_id, member_id),

	constraint ck_submissions_has_content check (content is not null or repository_url is not null),
	constraint ck_submissions_score check (score >= 0 and score <= 10),
	constraint ck_submissions_reviewed check ((score is null) = (reviewed_at is null))
);

create index idx_submissions_member_id on submissions(member_id);
